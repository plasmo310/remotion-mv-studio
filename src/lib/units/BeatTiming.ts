// ---------------------------------------------------------------------------
// 曲の速さ（BPM）で書いたタイミングを秒へ読み替える。
//
// 曲に合わせて動かすものは「0.4 秒ごと」より「1拍ごと」で書くほうが、
// 何をやりたかったのかが残るし、曲の速さが変わっても BPM だけ直せば全部ついてくる。
// 拍で書いた指定はここで秒へ直し、その先は既存の秒ベースの仕組みへ渡す。
// ---------------------------------------------------------------------------

/** 0 除算・逆走を避けるための最小 BPM */
const MIN_BPM = 0.0001;

/** 速さを曲の拍で指定する。秒の代わりにこれを渡せるところで使う */
export type BeatTempo = {
  /** 曲の速さ（1分あたりの拍数） */
  bpm: number;
  /** ひとつぶんを何拍もたせるか。0.5 で8分、2 で2拍ぶん。省略時 1（4分） */
  beats?: number;
};

/**
 * 1拍の長さ（秒）
 * @param bpm 曲の速さ（1分あたりの拍数）
 */
export const secPerBeat = (bpm: number): number => 60 / Math.max(bpm, MIN_BPM);

/**
 * 拍で書いた速さを、ひとつぶんの秒に直す
 * @param tempo 拍で書いた速さ
 */
export const beatTempoToSec = (tempo: BeatTempo): number =>
  secPerBeat(tempo.bpm) * (tempo.beats ?? 1);
